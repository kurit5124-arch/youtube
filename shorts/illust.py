def pick(text: str, n: int = 1, exclude: tuple[str, ...] = ()) -> list[str]:
    """文章に合うイラストを n 個選ぶ（見つからなければ空）。"""
    found: list[str] = []
    for kw, em in KEYWORDS:
        if kw in text and em not in found and em not in exclude:
            found.append(em)
            if len(found) >= n:
                break
    return found


def pick_one(text: str, fallback: str = "❓") -> str:
    got = pick(text, 1)
    return got[0] if got else fallback


@lru_cache(maxsize=1)
def _font_path() -> str | None:
    for p in EMOJI_FONTS:
        if Path(p).exists():
            return p
    return None


@lru_cache(maxsize=256)
def _render(ch: str) -> Image.Image | None:
    path = _font_path()
    if not path:
        return None
    try:
        font = ImageFont.truetype(path, 109)  # Noto Color Emoji はこの大きさで読み込む決まり
    except OSError:
        return None
    img = Image.new("RGBA", (160, 160), (0, 0, 0, 0))
    ImageDraw.Draw(img).text((80, 80), ch, font=font, embedded_color=True, anchor="mm")
    box = img.getbbox()
    return img.crop(box) if box else None


def image(ch: str, size: int, alpha: float = 1.0, angle: float = 0.0) -> Image.Image | None:
    """絵文字 ch を size ピクセルの画像にする（フォントが無ければ None）。"""
    base = _render(ch)
    if base is None:
        return None
    scale = size / max(base.size)
    im = base.resize((max(1, int(base.width * scale)), max(1, int(base.height * scale))), Image.LANCZOS)
    if angle:
        im = im.rotate(angle, resample=Image.BICUBIC, expand=True)
    if alpha < 1:
        a = im.getchannel("A").point(lambda v: int(v * alpha))
        im.putalpha(a)
    return im
